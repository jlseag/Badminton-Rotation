-- ═══════════════════════════════════════════════════════════════════════════
-- Badminton Rotation — admin panel, device tracking and audit
-- Run AFTER schema.sql. Idempotent; safe to re-run.
--
-- Admin power lives on the ACCOUNT, never in a key embedded in a page.
-- The admin panel signs in like any host and uses the same public key; the
-- policies below are what let an admin see more. Nothing secret ships to the
-- browser, so the page source is worthless to an attacker.
-- ═══════════════════════════════════════════════════════════════════════════

alter table hosts add column if not exists is_admin         boolean not null default false;
alter table hosts add column if not exists suspended        boolean not null default false;
alter table hosts add column if not exists suspended_reason text;
alter table hosts add column if not exists last_seen_at     timestamptz;

create or replace function is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from hosts where id = auth.uid() and is_admin);
$$;

-- A suspended host is never premium, whatever their entitlement says.
create or replace function is_premium(uid uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from entitlements e join hosts h on h.id = e.host_id
    where e.host_id = uid
      and not h.suspended
      and e.status in ('trial','active')
      and (e.expires_at is null or e.expires_at > now())
  );
$$;

-- ─── Nobody promotes themselves ───────────────────────────────────────────
-- RLS cannot compare old and new values, so a trigger guards the two columns
-- that matter. Only an existing admin (or the service role) may change them.
create or replace function guard_privileged_columns() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if (new.is_admin is distinct from old.is_admin
      or new.suspended is distinct from old.suspended)
     and not coalesce(is_admin(), false)
     and auth.uid() is not null then
    new.is_admin  := old.is_admin;
    new.suspended := old.suspended;
  end if;
  return new;
end $$;

drop trigger if exists hosts_guard on hosts;
create trigger hosts_guard before update on hosts
  for each row execute function guard_privileged_columns();

-- ─── Devices ──────────────────────────────────────────────────────────────
-- One row per browser that has signed in. device_key is generated by the app
-- and kept in localStorage. This is how you spot a shared account: one email,
-- five devices, all active on a Saturday morning.
create table if not exists devices (
  id          uuid primary key default gen_random_uuid(),
  host_id     uuid not null references hosts(id) on delete cascade,
  device_key  text not null,
  label       text,
  first_seen  timestamptz not null default now(),
  last_seen   timestamptz not null default now(),
  revoked     boolean not null default false,
  unique (host_id, device_key)
);
create index if not exists devices_host_idx on devices(host_id, last_seen desc);

-- ─── Audit log ────────────────────────────────────────────────────────────
-- Every change to an entitlement, and every admin action. You will want this
-- the first time a host says "I paid and you cut me off".
create table if not exists audit_log (
  id          bigint generated always as identity primary key,
  at          timestamptz not null default now(),
  actor       uuid references hosts(id) on delete set null,
  actor_email text,
  action      text not null,
  target_host uuid references hosts(id) on delete set null,
  detail      jsonb not null default '{}'::jsonb
);
create index if not exists audit_at_idx on audit_log(at desc);

create or replace function log_entitlement_change() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into audit_log (actor, actor_email, action, target_host, detail)
  values (auth.uid(),
          (select email from hosts where id = auth.uid()),
          case when tg_op = 'INSERT' then 'entitlement.create' else 'entitlement.change' end,
          new.host_id,
          jsonb_build_object(
            'from',   case when tg_op = 'UPDATE' then old.status::text end,
            'to',     new.status::text,
            'expires',new.expires_at,
            'source', new.source));
  return new;
end $$;

drop trigger if exists entitlements_audit on entitlements;
create trigger entitlements_audit after insert or update on entitlements
  for each row execute function log_entitlement_change();

-- ═══════════════════════════════════════════════════════════════════════════
-- Policies: admins see and change account-level data. Deliberately NOT
-- player names, rosters or match history — an admin account should not be
-- able to read a host's group data, so a compromised admin leaks far less.
-- ═══════════════════════════════════════════════════════════════════════════
alter table devices   enable row level security;
alter table audit_log enable row level security;

drop policy if exists hosts_self on hosts;
create policy hosts_select on hosts for select using (id = auth.uid() or is_admin());
create policy hosts_update on hosts for update
  using (id = auth.uid() or is_admin()) with check (id = auth.uid() or is_admin());
create policy hosts_insert on hosts for insert with check (id = auth.uid());

-- The one deliberate exception to "entitlements are unwritable": an admin may
-- grant and revoke. Gated on is_admin, which can only be set in SQL.
drop policy if exists entitlements_admin_write on entitlements;
create policy entitlements_read_admin on entitlements for select using (is_admin());
create policy entitlements_admin_write on entitlements for all
  using (is_admin()) with check (is_admin());

drop policy if exists devices_rw on devices;
create policy devices_own on devices for all
  using (host_id = auth.uid()) with check (host_id = auth.uid());
create policy devices_admin on devices for select using (is_admin());
create policy devices_admin_revoke on devices for update
  using (is_admin()) with check (is_admin());

create policy audit_admin_read on audit_log for select using (is_admin());

-- ═══════════════════════════════════════════════════════════════════════════
-- The dashboard view. security_invoker means RLS still applies, so a normal
-- host querying it sees only themselves; an admin sees everyone.
-- ═══════════════════════════════════════════════════════════════════════════
drop view if exists admin_overview;
create view admin_overview with (security_invoker = true) as
  select h.id,
         h.email,
         h.display_name,
         h.created_at                                   as joined,
         h.last_seen_at,
         h.suspended,
         h.is_admin,
         coalesce(e.status, 'free')                     as plan,
         e.expires_at,
         e.source,
         case when e.status = 'trial' and e.expires_at > now()
              then ceil(extract(epoch from e.expires_at - now()) / 86400)::int end
                                                        as trial_days_left,
         (select count(*) from devices d
           where d.host_id = h.id and not d.revoked)     as devices,
         (select count(*) from groups g where g.host_id = h.id)   as groups,
         (select count(*) from sessions s where s.host_id = h.id) as sessions,
         (select max(s.started_at) from sessions s where s.host_id = h.id)
                                                        as last_session
    from hosts h
    left join entitlements e on e.host_id = h.id;

